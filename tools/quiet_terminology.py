#!/usr/bin/env python3
# @(#)quiet-terminology / python / tools/quiet_terminology.py / 2026-10-23

"""Reference implementation of the Quiet port for Terminology.

Commands:

    vendor QUIET_DIR   copy Quiet's canonical anchors and resolved generic
                       terminal palette into vendor/quiet.json
    generate           write the color scheme INI files and contrast.adoc
    build EET          encode the INI files into .eet with EFL's eet tool
    check [EET]        fail if generated artifacts drifted or a required
                       relationship misses its contrast floor

The INI files use Terminology's own color scheme format. The .eet encoding
matches what Terminology's data/colorschemes/add_color_scheme.sh produces
from the same INI.
"""

import configparser
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VENDOR = ROOT / "vendor" / "quiet.json"
SCHEMES = ROOT / "colorschemes"
REPORT = ROOT / "contrast.adoc"

MODES = ("day", "night")
NAMES = {"day": "Quiet Day", "night": "Quiet Night"}

METADATA = {
    "version": 1,
    "author": "Joey D'Anna, after Quiet by Chris Mecca",
    "website": "https://github.com/jdanna/quiet-terminology",
    "license": "MIT",
}

ANSI_NAMES = ("black", "red", "green", "yellow",
              "blue", "magenta", "cyan", "white")

# Quiet Core's selection mix toward Mineral (internal/core/derive.go).
SELECTION_MIX = {"day": 0.10, "night": 0.23}

# Terminology's default theme draws the selection as a RECT with
# color 255 255 255 128 under color class GLOW (data/themes/default/
# selection.edc), stacked above the text grid.
SELECTION_PART_ALPHA = 128

# Faint colors: the share of each color kept over Field. 75 percent is the
# default of Terminology's data/colorschemes/gen_faint.py.
FAINT_KEEP = 0.75

TEXT = 4.5


# --- Color math -------------------------------------------------------------


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def hexstr(c):
    return "".join("%02X" % v for v in c)


def linear(v):
    v /= 255
    return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4


def luminance(h):
    r, g, b = (linear(v) for v in rgb(h))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def composite(fg, bg, alpha):
    """Legacy gamma-encoded sRGB "over", as Quiet's CompositeLegacySRGB."""
    return hexstr(
        round(f * alpha + b * (1 - alpha)) for f, b in zip(rgb(fg), rgb(bg))
    )


# --- Edje -------------------------------------------------------------------


def edje_alpha(class_alpha, part_alpha=SELECTION_PART_ALPHA):
    """Effective alpha of a part, as computed in edje_calc.c."""
    return ((class_alpha + 1) * part_alpha) >> 8


def selection_class_alpha(mode):
    """The smallest color class alpha whose effective selection alpha is not
    below Quiet Core's selection mix."""
    target = SELECTION_MIX[mode] * 255
    for a in range(256):
        if edje_alpha(a) >= target:
            return a
    raise ValueError(f"selection mix {SELECTION_MIX[mode]} unreachable")


# --- Mapping ----------------------------------------------------------------


def resolve(mode, quiet):
    a = quiet["anchors"]
    t = quiet["terminal"]
    field, ink, muted = a["field"], a["ink"], a["muted"]
    mineral, ochre = a["mineral"], a["ochre"]

    def block(default, colors):
        return {
            "def": default,
            **dict(zip(ANSI_NAMES, colors)),
            "inverse_fg": field,
            "inverse_bg": default,
        }

    def faint(colors):
        return [composite(c, field, FAINT_KEEP) for c in colors]

    normal = t["ansi"][:8]
    bright = t["ansi"][8:]
    main_alpha = selection_class_alpha(mode)

    return {
        "Colors": {
            "bg": field,
            "main": mineral + "%02X" % main_alpha,
            "hl": t["cursor"],
            "end_sel": mineral,
            "tab_missed_1": ochre,
            "tab_missed_2": field,
            "tab_missed_3": field,
            "tab_missed_over_1": ochre,
            "tab_missed_over_2": field,
            "tab_missed_over_3": field,
            "tab_title_2": field,
        },
        "Normal": block(t["text"], normal),
        "Bright": block(t["bold"], bright),
        "Faint": block(muted, faint(normal)),
        "BrightFaint": block(muted, faint(bright)),
    }


# --- INI and EET description ------------------------------------------------


def render_ini(mode, scheme):
    out = [
        f"# @(#)quiet-terminology / ini / colorschemes/{NAMES[mode]}.ini / generated",
        "# Generated by tools/quiet_terminology.py. Do not edit.",
        "",
        "[Main]",
        "version = 1",
        "",
        "[Metadata]",
        f"version = {METADATA['version']}",
        f"name = {NAMES[mode]}",
        f"author = {METADATA['author']}",
        f"website = {METADATA['website']}",
        f"license = {METADATA['license']}",
    ]
    for section, colors in scheme.items():
        out += ["", f"[{section}]"]
        out += [f"{key} = #{value.lower()}" for key, value in colors.items()]
    return "\n".join(out) + "\n"


def parse_color(value):
    """Parse a color the way Terminology's ini2desc.py does."""
    h = value.lstrip("#")
    r, g, b = rgb(h[:6])
    a = int(h[6:8], 16) if len(h) == 8 else 255
    if a != 255 and (a > r or a > g or a > b):
        r, g, b = (r * a) // 255, (g * a) // 255, (b * a) // 255
    return r, g, b, a


def render_desc(ini_text):
    """EET data description, byte for byte what ini2desc.py writes."""
    cfg = configparser.ConfigParser()
    cfg.read_string(ini_text)
    out = []

    def color(value):
        r, g, b, a = parse_color(value)
        out.append('        group "Color" struct {\n')
        out.append(f'            value "r" uchar: {r};\n')
        out.append(f'            value "g" uchar: {g};\n')
        out.append(f'            value "b" uchar: {b};\n')
        out.append(f'            value "a" uchar: {a};\n')
        out.append("        }\n")

    def named(section, key, default=None):
        out.append(f'    group "{key}" struct {{\n')
        color(cfg.get(section, key, fallback=default))
        out.append("    }\n")

    out.append('group "Color_Scheme" struct {\n')
    out.append(f'    value "version" int: {cfg.get("Main", "version", fallback="1")};\n')
    out.append(f'    value "md.version" int: {cfg.get("Metadata", "version", fallback="1")};\n')
    out.append(f'    value "md.name" string: "{cfg["Metadata"]["name"]}";\n')
    out.append(f'    value "md.author" string: "{cfg["Metadata"]["author"]}";\n')
    out.append(f'    value "md.website" string: "{cfg.get("Metadata", "website", fallback="")}";\n')
    out.append(f'    value "md.license" string: "{cfg["Metadata"]["license"]}";\n')
    for key, default in (
        ("def", "#aaaaaa"), ("bg", "#202020"), ("fg", "#aaaaaa"),
        ("main", "#3599ff"), ("hl", "#ffffff"), ("end_sel", "#ff3300"),
        ("tab_missed_1", "#ff9933"), ("tab_missed_2", "#ff3300"),
        ("tab_missed_3", "#ff0000"), ("tab_missed_over_1", "#ffff40"),
        ("tab_missed_over_2", "#ff9933"), ("tab_missed_over_3", "#ff0000"),
        ("tab_title_2", "#000000"),
    ):
        named("Colors", key, default)
    for section in ("Normal", "Bright", "Faint"):
        out.append(f'    group "{section}" struct {{\n')
        out.append('    group "Color_Block" struct {\n')
        for key in ("def", *ANSI_NAMES, "inverse_fg", "inverse_bg"):
            named(section, key)
        out.append("    }\n")
        out.append("    }\n")
    out.append("}\n")
    return "".join(out)


# --- Contrast report --------------------------------------------------------


def relationships(mode, quiet, scheme):
    """Rendered relationships, with a floor where one is required."""
    field = scheme["Colors"]["bg"]
    main = scheme["Colors"]["main"]
    alpha = edje_alpha(int(main[6:], 16)) / 255

    def selected(c):
        return composite(main[:6], c, alpha)

    sel = selected(field)
    rows = [
        ("Default text", scheme["Normal"]["def"], field, 7.0),
        ("Bold default text", scheme["Bright"]["def"], field, 7.0),
        ("Faint default text", scheme["Faint"]["def"], field, TEXT),
        ("Reverse video", scheme["Normal"]["inverse_fg"],
         scheme["Normal"]["inverse_bg"], 7.0),
        ("Selected default text", selected(scheme["Normal"]["def"]), sel, TEXT),
    ]
    neutral = {"day": {"black", "white"}, "night": {"black", "white"}}[mode]
    for section, label in (("Normal", ""), ("Bright", "bright ")):
        for name in ANSI_NAMES:
            floor = None if name in neutral else TEXT
            rows.append((f"ANSI {label}{name}", scheme[section][name], field, floor))
    for name in ANSI_NAMES[1:7]:
        rows.append((f"Faint {name}", scheme["Faint"][name], field, None))
    for name in ANSI_NAMES[1:7]:
        rows.append((f"Selected {name}", selected(scheme["Normal"][name]), sel, None))
    return sel, [
        {"role": role, "fg": fg, "bg": bg, "ratio": contrast(fg, bg), "floor": floor}
        for role, fg, bg, floor in rows
    ]


def render_report(vendor, schemes):
    src = vendor["source"]
    out = [
        "// @(#)quiet-terminology / asciidoc / contrast.adoc / generated",
        "// Generated by tools/quiet_terminology.py. Do not edit.",
        "",
        "= Quiet for Terminology: rendered contrast",
        "",
        "WCAG 2.x contrast of the colors Terminology draws with the Quiet",
        "schemes.",
        "Selected colors are composited the way Terminology's default theme",
        "draws its selection: Mineral, at the effective Edje alpha, over both",
        "the text and its ground.",
        "",
        f"Source: Quiet `{src['commit'][:7]}`.",
        "",
        "ANSI black and white have no floor.",
        "They are neutral slots that the generic terminal mapping allows to",
        "approach Field.",
        "",
    ]
    for mode in MODES:
        scheme = schemes[mode]
        sel, rows = relationships(mode, vendor["modes"][mode], scheme)
        main = scheme["Colors"]["main"]
        eff = edje_alpha(int(main[6:], 16))
        out += [
            f"== {NAMES[mode]}",
            "",
            f"Selection ground: `#{sel}` "
            f"(`main` alpha {int(main[6:], 16)}, effective {eff}/255).",
            "",
            '[cols="3,1,1,1,1",options="header"]',
            "|===",
            "| Role | Text | Ground | Ratio | Floor",
            "",
        ]
        for row in rows:
            floor = "" if row["floor"] is None else f"{row['floor']:.1f}"
            out += [
                f"| {row['role']}",
                f"| `#{row['fg']}`",
                f"| `#{row['bg']}`",
                f"| {row['ratio']:.2f}",
                f"| {floor}",
                "",
            ]
        out += ["|===", ""]
    return "\n".join(out).rstrip() + "\n"


# --- Commands ---------------------------------------------------------------


def load_vendor():
    return json.loads(VENDOR.read_text())


def generated(vendor):
    schemes = {m: resolve(m, vendor["modes"][m]) for m in MODES}
    files = {
        SCHEMES / f"{NAMES[m]}.ini": render_ini(m, schemes[m]) for m in MODES
    }
    files[REPORT] = render_report(vendor, schemes)
    return schemes, files


def encode(eet, ini_path, out_path):
    with tempfile.TemporaryDirectory() as tmp:
        desc = Path(tmp) / "desc"
        desc.write_text(render_desc(ini_path.read_text()))
        target = Path(tmp) / "out.eet"
        subprocess.run(
            [eet, "-e", str(target), ini_path.stem, str(desc), "1"],
            check=True, capture_output=True,
        )
        shutil.copyfile(target, out_path)


def parse_kitty(path):
    keys = {}
    for line in path.read_text().splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[1].startswith("#"):
            keys[parts[0]] = parts[1][1:].upper()
    return keys


def cmd_vendor(quiet_dir):
    quiet_dir = Path(quiet_dir)
    commit = subprocess.run(
        ["git", "-C", str(quiet_dir), "rev-parse", "HEAD"],
        capture_output=True, text=True, check=True,
    ).stdout.strip()
    modes = {}
    for mode in MODES:
        spec = json.loads((quiet_dir / "spec" / f"quiet-{mode}.json").read_text())
        kitty = parse_kitty(quiet_dir / "ports" / "kitty" / f"{NAMES[mode]}.conf")
        anchors = {k: v.lstrip("#").upper() for k, v in spec["anchors"].items()}
        modes[mode] = {
            "anchors": anchors,
            "terminal": {
                "background": kitty["background"],
                "text": kitty["foreground"],
                # Quiet's generic terminal model sets Bold to Ink.
                "bold": anchors["ink"],
                "cursor": kitty["cursor"],
                "ansi": [kitty[f"color{i}"] for i in range(16)],
            },
        }
    doc = {
        "source": {
            "repository": "quiet",
            "commit": commit,
            "anchors": "spec/quiet-{day,night}.json",
            "terminal": "ports/kitty/Quiet {Day,Night}.conf",
        },
        "modes": modes,
    }
    VENDOR.parent.mkdir(exist_ok=True)
    VENDOR.write_text(json.dumps(doc, indent=2) + "\n")
    print(f"wrote {VENDOR.relative_to(ROOT)} from quiet {commit[:7]}")


def cmd_generate():
    _, files = generated(load_vendor())
    for path, text in files.items():
        path.parent.mkdir(exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")


def cmd_build(eet):
    for mode in MODES:
        ini = SCHEMES / f"{NAMES[mode]}.ini"
        out = ini.with_suffix(".eet")
        encode(eet, ini, out)
        print(f"wrote {out.relative_to(ROOT)}")


def cmd_check(eet=None):
    vendor = load_vendor()
    schemes, files = generated(vendor)
    ok = True

    for path, text in files.items():
        if not path.exists() or path.read_text() != text:
            print(f"drift: {path.relative_to(ROOT)} (run make generate)")
            ok = False

    for mode in MODES:
        quiet = vendor["modes"][mode]
        scheme = schemes[mode]

        # Terminology's ini2desc.py premultiplies a translucent color when
        # its alpha exceeds a channel. Edje expects straight alpha, so the
        # translucent colors must never trigger that.
        for section, colors in scheme.items():
            for key, value in colors.items():
                if len(value) == 8 and parse_color(value)[:3] != rgb(value[:6]):
                    print(f"premultiplied by ini2desc: {mode} {section}.{key}")
                    ok = False

        if scheme["Normal"]["black"] != quiet["terminal"]["ansi"][0]:
            print(f"palette: {mode} does not use the generic terminal palette")
            ok = False

        for row in relationships(mode, quiet, scheme)[1]:
            if row["floor"] is not None and row["ratio"] < row["floor"]:
                print(f"contrast: {mode} {row['role']} {row['ratio']:.2f}"
                      f" < {row['floor']}")
                ok = False

    if eet:
        with tempfile.TemporaryDirectory() as tmp:
            for mode in MODES:
                ini = SCHEMES / f"{NAMES[mode]}.ini"
                committed = ini.with_suffix(".eet")
                fresh = Path(tmp) / committed.name
                encode(eet, ini, fresh)
                if not committed.exists() or \
                        committed.read_bytes() != fresh.read_bytes():
                    print(f"drift: {committed.relative_to(ROOT)} (run make build)")
                    ok = False

    if not ok:
        return 1
    print("ok")
    return 0


def main(argv):
    if argv[:1] == ["vendor"] and len(argv) == 2:
        cmd_vendor(argv[1])
    elif argv == ["generate"]:
        cmd_generate()
    elif argv[:1] == ["build"] and len(argv) == 2:
        cmd_build(argv[1])
    elif argv[:1] == ["check"] and len(argv) <= 2:
        return cmd_check(argv[1] if len(argv) == 2 else None)
    else:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
